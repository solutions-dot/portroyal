/* Shared story data, with every carry/place task declared visibly. */
const t = (place, goal, ids, next, journal) => ({
  place,
  goal,
  needs: { talk: ids },
  next,
  journal,
});
const d = (place, goal, ids, next, journal) => ({
  place,
  goal,
  needs: { do: ids.map((id) => ({ id, carry: id })) },
  next,
  journal,
});
const g = (place, goal, id, next) => ({
  place,
  goal,
  needs: { go: [id] },
  next,
});
const w = (place, goal, card, next, extra = {}) => ({
  place,
  goal,
  wait: true,
  card,
  next,
  ...extra,
});
